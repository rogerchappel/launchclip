#!/usr/bin/env node
// Measures every drawing style of the characters kit the way a reference is
// measured (src/drawing_traits.js) and writes src/drawing_style_profiles.js,
// the table `style create --from-reference` matches a reference against.
// Run it after a drawing style is added or redrawn:
//
//   node scripts/measure-drawing-styles.mjs
//
// Each style draws the example cast (examples/story/characters-16x9) on a
// cast sheet in Chromium (Playwright, as `launchclip cast sheet` does); the
// top of the sheet (two rows of poses) is measured.
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DRAWING_STYLES } from "@launchclip/core/characters/styles.mjs";
import { castSheet } from "../src/cast.js";
import { drawingTraits, measureDrawing } from "../src/drawing_traits.js";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const story = JSON.parse(await readFile(path.join(root, "examples/story/characters-16x9/storyboard.json"), "utf8"));
const work = await mkdtemp(path.join(os.tmpdir(), "launchclip-drawing-styles-"));
const profiles = {};
try {
  for (const style of DRAWING_STYLES) {
    const dir = path.join(work, style);
    execFileSync("mkdir", ["-p", dir]);
    await writeFile(path.join(dir, "storyboard.json"), JSON.stringify({ ...story, cast: { ...story.cast, style } }));
    const sheet = await castSheet(path.join(dir, "storyboard.json"));
    const crop = path.join(dir, "poses.png");
    execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-i", sheet.png, "-vf", "crop=1100:810:30:110", crop]);
    const { traits } = drawingTraits(await measureDrawing(crop, { image: true }));
    profiles[style] = { outline: traits.outline ?? null, fill: traits.fill ?? null, grain: traits.grain ?? null };
    console.log(style, JSON.stringify(profiles[style]));
  }
} finally {
  await rm(work, { recursive: true, force: true });
}
const body = `// Generated by scripts/measure-drawing-styles.mjs: do not edit by hand.
// Every drawing style of the characters kit (kit/core/characters/styles.mjs),
// measured on a cast sheet the way a reference is measured
// (src/drawing_traits.js). src/drawing_match.js matches a reference's traits
// against these. A style missing here has not been measured yet.
export const DRAWING_STYLE_PROFILES = Object.freeze(${JSON.stringify(profiles, null, 2)});
`;
await writeFile(path.join(root, "src/drawing_style_profiles.js"), body);
console.log(`wrote src/drawing_style_profiles.js (${Object.keys(profiles).length} styles)`);
