#!/usr/bin/env node
// Builds RIG_RUNTIME (kit/hyperframes/rig-runtime.mjs): the per-frame rig
// painter (kit/hyperframes/rig-scene-paint.mjs) and the kit/core rig code it
// imports as one IIFE string that HyperFrames inlines once per page,
// defining window.lcRigScene(host, plan, prepared, t, canvas), the same code
// Remotion imports. Rerun after changing the rig (kit/core/characters) or the
// tree serialiser; test/rig_scene_layer.test.js fails while the file is stale.
//
//   node scripts/rig-runtime.mjs
import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const RUNTIME_FILE = `${ROOT}kit/hyperframes/rig-runtime.mjs`;

/** The runtime module's source text. */
export async function rigRuntimeSource() {
  const result = await build({entryPoints: [`${ROOT}kit/hyperframes/rig-scene-paint.mjs`], bundle: true, write: false, format: 'iife', globalName: 'lcRigBundle', minify: true, legalComments: 'none', target: 'es2020', logLevel: 'silent'});
  const code = `window.lcRigScene = window.lcRigScene || (function () {\n${result.outputFiles[0].text}return lcRigBundle.paintRigScene;\n})();`;
  return `// GENERATED by scripts/rig-runtime.mjs from kit/hyperframes/rig-scene-paint.mjs; do not edit.
// The per-frame rig painter and the kit/core rig code as one script
// HyperFrames inlines; it defines window.lcRigScene.
export const RIG_RUNTIME = ${JSON.stringify(code)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(RUNTIME_FILE, await rigRuntimeSource());
  console.log(`wrote ${RUNTIME_FILE}`);
}
