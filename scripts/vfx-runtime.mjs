#!/usr/bin/env node
// Builds VFX_RUNTIME (kit/core/vfx/runtime.mjs): kit/core/vfx/paint.mjs and the
// vendored effects as one IIFE string that HyperFrames inlines into a page,
// defining window.lcVfx.paint, the same code Remotion imports. Rerun after
// changing anything under kit/core/vfx; test/vfx_layer.test.js fails while
// the file is stale.
//
//   node scripts/vfx-runtime.mjs
import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const RUNTIME_FILE = `${ROOT}kit/core/vfx/runtime.mjs`;
const NOTICE = '/*! LaunchClip VFX runtime. Bundles pixelfx 0.3.1 (https://github.com/patch-gg/pixelfx), MIT License, Copyright (c) 2026 Patch, Copyright (c) 2026 Hugo Duprez; parts adapted from Sprite Fusion pixel art VFX, MIT License, Copyright (c) 2026 Hugo Duprez. Full licence text: kit/core/vfx/vendor/LICENSE. */';

/** The runtime module's source text. */
export async function vfxRuntimeSource() {
  const result = await build({entryPoints: [`${ROOT}kit/core/vfx/paint.mjs`], bundle: true, write: false, format: 'iife', globalName: 'lcVfxBundle', minifyWhitespace: true, legalComments: 'none', target: 'es2020', logLevel: 'silent'});
  const code = `${NOTICE}\nwindow.lcVfx = window.lcVfx || (function () {\n${result.outputFiles[0].text}return {paint: lcVfxBundle.paintVfx, words: lcVfxBundle.paintVfxWords};\n})();`;
  return `// GENERATED by scripts/vfx-runtime.mjs from kit/core/vfx/paint.mjs; do not edit.
// The VFX painter and the vendored effects (kit/core/vfx/vendor: pixelfx 0.3.1,
// MIT License, Copyright (c) 2026 Patch, Copyright (c) 2026 Hugo Duprez) as
// one script HyperFrames inlines; it defines window.lcVfx.paint and .words.
export const VFX_RUNTIME = ${JSON.stringify(code)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(RUNTIME_FILE, await vfxRuntimeSource());
  console.log(`wrote ${RUNTIME_FILE}`);
}
