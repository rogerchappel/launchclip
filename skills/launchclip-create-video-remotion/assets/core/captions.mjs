// Word captions core: chunk measured narration words into short-form caption
// lines, plus the seek-safe GSAP runtime and CSS the HyperFrames compiler
// mounts. Plain ESM with no imports, so the Remotion kit
// (kit/remotion/captions/WordCaptions.tsx) uses the same chunking, band and
// timing. The CLI wrapper is word-captions.mjs in the create-video skills.
//
// Canonical copy: kit/core/captions.mjs.

const STRONG_BREAK = /[.!?…]$/;
const SOFT_BREAK = /[,;:—–-]$/;

// Caption motion, shared by the GSAP runtime below and WordCaptions.tsx so
// both renderers pop, highlight and clear identically.
