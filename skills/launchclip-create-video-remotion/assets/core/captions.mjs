  lineIn: Object.freeze({ from: Object.freeze({ opacity: 0, y: 26, scale: 0.86 }), duration: 0.16, ease: 'back.out(2.2)' }),
  wordOn: Object.freeze({ lead: 0.03, scale: 1.08, duration: 0.06, ease: 'power2.out' }),
