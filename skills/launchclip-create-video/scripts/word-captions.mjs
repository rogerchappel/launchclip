#!/usr/bin/env node
// Turn measured narration word timings into short-form caption chunks plus a
// deterministic, seek-safe HyperFrames/GSAP runtime that highlights the active
// word. Usage:
//   node word-captions.mjs <NARRATION.json> <out-dir> [--max-words 3] [--max-chars 18]
// NARRATION.json may be {words:[{text,start,end}]} or a flat array of words.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const STRONG_BREAK = /[.!?…]$/;
const SOFT_BREAK = /[,;:—–-]$/;

export function chunkWords(words, { maxWords = 3, maxChars = 18, gapSeconds = 0.28 } = {}) {
  const clean = words
    .map((word) => ({ text: String(word.text ?? word.word ?? '').trim(), start: Number(word.start), end: Number(word.end) }))
    .filter((word) => word.text && Number.isFinite(word.start) && Number.isFinite(word.end) && word.end >= word.start);
  const chunks = [];
  let current = [];
  const flush = () => {
    if (!current.length) return;
    chunks.push({ start: current[0].start, end: current.at(-1).end, words: current });
    current = [];
  };
  for (const word of clean) {
    const previous = current.at(-1);
    const length = current.reduce((sum, entry) => sum + entry.text.length + 1, 0) + word.text.length;
    if (previous && (word.start - previous.end > gapSeconds || current.length >= maxWords || length > maxChars)) flush();
    current.push(word);
    if (STRONG_BREAK.test(word.text) || (SOFT_BREAK.test(word.text) && current.length > 1)) flush();
  }
  flush();
  // Hold each chunk until the next one starts (or briefly past its last word)
  // so captions never blink off between closely spaced phrases.
  return chunks.map((chunk, index) => {
    const next = chunks[index + 1];
    const hold = next ? Math.min(next.start, chunk.end + 0.6) : chunk.end + 0.4;
    return { id: `cap-${String(index + 1).padStart(3, '0')}`, start: round(chunk.start), end: round(Math.max(hold, chunk.end)), words: chunk.words.map((word) => ({ text: word.text, start: round(word.start), end: round(word.end) })) };
  });
}

export function captionRuntime(chunks) {
  return `// Generated by word-captions.mjs. Call mountCaptions(tl, container) while
// building the paused root timeline; everything is created synchronously.
(function () {
  var CHUNKS = ${JSON.stringify(chunks)};
  window.mountCaptions = function (tl, container, opts) {
    opts = opts || {};
    var hidden = opts.hide || [];
    function isHidden(t) { for (var i = 0; i < hidden.length; i++) if (t >= hidden[i][0] && t < hidden[i][1]) return true; return false; }
    CHUNKS.forEach(function (chunk) {
      if (isHidden(chunk.start)) return;
      var line = document.createElement('div');
      line.className = 'lc-cap';
      line.id = chunk.id;
      chunk.words.forEach(function (word, i) {
        var span = document.createElement('span');
        span.className = 'lc-cap-w';
        span.id = chunk.id + '-w' + i;
        span.textContent = word.text;
        line.appendChild(span);
      });
      container.appendChild(line);
      tl.fromTo(line, { opacity: 0, y: 26, scale: 0.86 }, { opacity: 1, y: 0, scale: 1, duration: 0.16, ease: 'back.out(2.2)' }, chunk.start);
      chunk.words.forEach(function (word, i) {
        var span = line.children[i];
        tl.fromTo(span, { color: 'var(--cap-idle)', scale: 1 }, { color: 'var(--cap-active)', scale: 1.08, duration: 0.07, ease: 'power2.out' }, word.start);
        tl.to(span, { color: 'var(--cap-spoken)', scale: 1, duration: 0.12, ease: 'power1.out' }, Math.max(word.end, word.start + 0.08));
      });
      tl.to(line, { opacity: 0, y: -10, duration: 0.1, ease: 'power2.in' }, Math.max(chunk.start + 0.12, chunk.end - 0.1));
    });
  };
})();
`;
}

export const CAPTION_CSS = `.lc-captions { position: absolute; left: 6%; right: 15%; top: 62%; height: 12%; display: flex; align-items: center; justify-content: center; pointer-events: none; z-index: 50; }
.lc-cap { position: absolute; display: flex; gap: 0.42em; flex-wrap: wrap; justify-content: center; font: 900 74px/1.05 var(--cap-font, system-ui); letter-spacing: -0.01em; text-transform: uppercase; opacity: 0; }
.lc-cap-w { display: inline-block; color: var(--cap-idle); paint-order: stroke fill; -webkit-text-stroke: 10px rgba(0,0,0,.92); text-shadow: 0 6px 0 rgba(0,0,0,.55), 0 12px 28px rgba(0,0,0,.45); transform-origin: 50% 70%; }
`;

function round(value) { return Math.round(value * 1000) / 1000; }

async function main(argv) {
  const [input, outDir, ...rest] = argv;
  if (!input || !outDir) throw new Error('usage: word-captions.mjs <NARRATION.json> <out-dir> [--max-words N] [--max-chars N]');
  const flag = (name, fallback) => { const index = rest.indexOf(name); return index >= 0 ? Number(rest[index + 1]) : fallback; };
  const data = JSON.parse(await readFile(input, 'utf8'));
  const words = Array.isArray(data) ? data : data.words;
  if (!Array.isArray(words) || !words.length) throw new Error('No word timings found; captions need measured words, not segment-only times.');
  const chunks = chunkWords(words, { maxWords: flag('--max-words', 3), maxChars: flag('--max-chars', 18) });
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, 'captions.json'), `${JSON.stringify({ schema_version: 'launchclip.word-captions.v1', chunks }, null, 2)}\n`);
  await writeFile(path.join(outDir, 'captions.js'), captionRuntime(chunks));
  await writeFile(path.join(outDir, 'captions.css'), CAPTION_CSS);
  const covered = chunks.reduce((sum, chunk) => sum + chunk.words.length, 0);
  console.log(JSON.stringify({ chunks: chunks.length, words: covered, coverage: covered / words.length }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2)).catch((error) => { console.error(error.message); process.exit(1); });
